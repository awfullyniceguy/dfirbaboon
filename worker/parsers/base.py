"""Base interfaces and factory registry for dfirbaboon forensic parsers."""

from __future__ import annotations

import logging
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Type

try:
    from config import WorkerConfig
except ImportError:
    from worker.config import WorkerConfig


@dataclass
class ParserContext:
    """Execution context provided to parsers during analysis.

    Attributes:
        incident_id: Case / Incident identifier (e.g., INC10001).
        evidence_file: Original filename of the disk artifact.
        evidence_path: Absolute local filesystem path to the evidence file.
        scratch_dir: Base workspace working directory.
        config: Immutable runtime WorkerConfig.
        checkpoint_callback: Optional callable for streaming intermediate artifacts to S3.
        shared_state: Mutable dictionary for passing intermediate state between pipeline phases.
    """

    incident_id: str
    evidence_file: str
    evidence_path: Path
    scratch_dir: Path
    config: WorkerConfig
    checkpoint_callback: Optional[Callable[[Path, str], None]] = None
    shared_state: Dict[str, Any] = field(default_factory=dict)


@dataclass
class ParserResult:
    """Standardized result returned by all forensic parsers.

    Attributes:
        parser_name: Unique identifier of the parser.
        parser_type: Category of parser (e.g., filesystem, carver, scanner).
        status: Status code ("SUCCESS", "PARTIAL", "FAILED", "SKIPPED").
        start_time_utc: ISO 8601 UTC timestamp of execution start.
        end_time_utc: ISO 8601 UTC timestamp of execution end.
        duration_seconds: Elapsed execution time in seconds.
        output_files: List of paths to artifacts generated by this parser.
        metrics: Dictionary of numerical / categorical forensic counts (e.g. files carved, rows parsed).
        warnings: List of diagnostic or non-fatal warning messages.
        errors: List of fatal or non-fatal error messages encountered.
        details: Generic payload for phase-specific structured data.
    """

    parser_name: str
    parser_type: str
    status: str = "SUCCESS"
    start_time_utc: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    end_time_utc: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    duration_seconds: float = 0.0
    output_files: List[Path] = field(default_factory=list)
    metrics: Dict[str, Any] = field(default_factory=dict)
    warnings: List[str] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)
    details: Dict[str, Any] = field(default_factory=dict)


class BaseParser(ABC):
    """Abstract Base Class for modular DFIR pipeline parsers."""

    def __init__(self, config: WorkerConfig) -> None:
        self.config = config
        self.logger = logging.getLogger(f"dfirbaboon.{self.get_parser_name()}")

    @abstractmethod
    def get_parser_name(self) -> str:
        """Return the unique string identifier for this parser."""
        pass

    @abstractmethod
    def get_parser_type(self) -> str:
        """Return the category of parser (e.g. 'filesystem', 'carver', 'scanner')."""
        pass

    @abstractmethod
    def validate(self, evidence_path: Path) -> bool:
        """Verify whether this parser can process the provided evidence file."""
        pass

    @abstractmethod
    def parse(self, context: ParserContext) -> ParserResult:
        """Execute forensic extraction/analysis over the evidence artifact."""
        pass

    def safe_parse(self, context: ParserContext) -> ParserResult:
        """Execute parse() with complete exception containment and standardized timing."""
        start_dt = datetime.now(timezone.utc)
        result = ParserResult(
            parser_name=self.get_parser_name(),
            parser_type=self.get_parser_type(),
            start_time_utc=start_dt.isoformat(),
        )

        try:
            if not self.validate(context.evidence_path):
                self.logger.info(
                    "Validation skipped parser %s for evidence %s",
                    self.get_parser_name(),
                    context.evidence_path.name,
                )
                result.status = "SKIPPED"
                result.warnings.append(f"Evidence {context.evidence_path.name} not applicable for {self.get_parser_name()}")
                return result

            self.logger.info("Executing parser: %s", self.get_parser_name())
            result = self.parse(context)

        except Exception as exc:
            self.logger.exception("Uncaught exception in parser %s: %s", self.get_parser_name(), exc)
            result.status = "FAILED"
            result.errors.append(f"Uncaught exception: {str(exc)}")

        finally:
            end_dt = datetime.now(timezone.utc)
            result.end_time_utc = end_dt.isoformat()
            result.duration_seconds = round((end_dt - start_dt).total_seconds(), 3)

        return result


class ParserFactory:
    """Registry and factory for dynamically discovering and instantiating forensic parsers."""

    _registry: Dict[str, Type[BaseParser]] = {}

    @classmethod
    def register(cls, name: str, parser_cls: Type[BaseParser]) -> None:
        """Register a parser class under a given unique name."""
        cls._registry[name.lower()] = parser_cls

    @classmethod
    def create_parser(cls, name: str, config: WorkerConfig) -> BaseParser:
        """Instantiate a registered parser with the provided configuration."""
        key = name.lower()
        if key not in cls._registry:
            raise KeyError(f"Parser '{name}' is not registered. Available parsers: {list(cls._registry.keys())}")
        return cls._registry[key](config)

    @classmethod
    def get_registered_parsers(cls) -> List[str]:
        """Return a list of all registered parser names."""
        return list(cls._registry.keys())
